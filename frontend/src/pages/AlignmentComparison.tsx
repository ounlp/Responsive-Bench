import { useEffect, useMemo, useState } from "react";
import { Link as RouterLink } from "react-router-dom";
import Alert from "@mui/material/Alert";
import Box from "@mui/material/Box";
import CircularProgress from "@mui/material/CircularProgress";
import FormControl from "@mui/material/FormControl";
import InputLabel from "@mui/material/InputLabel";
import Link from "@mui/material/Link";
import MenuItem from "@mui/material/MenuItem";
import Select, { type SelectChangeEvent } from "@mui/material/Select";
import Typography from "@mui/material/Typography";
import { AlignmentResultsTable } from "../components/HumanAlignmentTable";
import {
  fetchHumanAlignmentByFile,
  fetchHumanAlignmentIndex,
  type HumanAlignmentData,
  type HumanAlignmentIndex,
} from "../data";

export default function AlignmentComparison() {
  const [index, setIndex] = useState<HumanAlignmentIndex | null>(null);
  const [indexError, setIndexError] = useState<string | null>(null);
  const [selectedFile, setSelectedFile] = useState<string>("");

  // Cache fetched variants so re-selecting one already viewed doesn't re-fetch.
  const [cache, setCache] = useState<Record<string, HumanAlignmentData>>({});
  const [dataError, setDataError] = useState<string | null>(null);
  const [dataLoading, setDataLoading] = useState(false);

  useEffect(() => {
    fetchHumanAlignmentIndex()
      .then((idx) => {
        setIndex(idx);
        const defaultVariant =
          idx?.variants.find((v) => v.file === "human_alignment.json") ??
          idx?.variants[0];
        if (defaultVariant) setSelectedFile(defaultVariant.file);
      })
      .catch((e) => setIndexError(e instanceof Error ? e.message : String(e)));
  }, []);

  useEffect(() => {
    if (!selectedFile || cache[selectedFile]) return;
    setDataLoading(true);
    setDataError(null);
    fetchHumanAlignmentByFile(selectedFile)
      .then((d) => {
        setCache((prev) => ({ ...prev, [selectedFile]: d }));
        setDataLoading(false);
      })
      .catch((e) => {
        setDataError(e instanceof Error ? e.message : String(e));
        setDataLoading(false);
      });
  }, [selectedFile, cache]);

  const selectedData = selectedFile ? cache[selectedFile] : undefined;
  const selectedEntry = useMemo(
    () => index?.variants.find((v) => v.file === selectedFile),
    [index, selectedFile],
  );

  const handleChange = (e: SelectChangeEvent) => {
    setSelectedFile(e.target.value);
  };

  return (
    <section>
      <Box sx={{ mb: 2 }}>
        <Link component={RouterLink} to="/" underline="hover" variant="body2">
          ← Back
        </Link>
      </Box>

      <Typography variant="h5" component="h2" gutterBottom>
        Judge Model Comparison
      </Typography>
      <Typography variant="body2" color="text.secondary" paragraph>
        Compares the same human annotations against different LLM judge models. Each
        option is a separate export generated by{" "}
        <Typography component="span" variant="body2" sx={{ fontFamily: "monospace" }}>
          scripts/export_human_alignment.py --eval-override RUN_ID=EVAL_ID
        </Typography>{" "}
        — the default run's results are never overwritten by a new comparison.
      </Typography>

      {indexError && <Alert severity="error" sx={{ mb: 2 }}>{indexError}</Alert>}

      {index && index.variants.length === 0 && (
        <Alert severity="info" sx={{ mb: 2 }}>
          No alignment variants found. Run{" "}
          <Typography component="span" variant="body2" sx={{ fontFamily: "monospace" }}>
            python scripts/export_human_alignment.py
          </Typography>{" "}
          to generate the default comparison.
        </Alert>
      )}

      {index && index.variants.length > 0 && (
        <>
          <FormControl size="small" sx={{ minWidth: 320, mb: 1 }}>
            <InputLabel id="judge-variant-label">Judge model</InputLabel>
            <Select
              labelId="judge-variant-label"
              label="Judge model"
              value={selectedFile}
              onChange={handleChange}
            >
              {index.variants.map((v) => (
                <MenuItem key={v.file} value={v.file}>
                  {v.label}
                  {v.n_matched_samples != null ? ` (n=${v.n_matched_samples})` : ""}
                </MenuItem>
              ))}
            </Select>
          </FormControl>

          {selectedEntry?.judge_models && (
            <Typography variant="body2" color="text.secondary" sx={{ mb: 2 }}>
              Judge per run:{" "}
              {Object.entries(selectedEntry.judge_models)
                .map(([runId, model]) => `${runId} → ${model ?? "—"}`)
                .join("  |  ")}
            </Typography>
          )}
        </>
      )}

      {dataLoading && (
        <Typography component="p" sx={{ display: "flex", alignItems: "center", gap: 1, mt: 2 }}>
          <CircularProgress size={20} /> Loading alignment data…
        </Typography>
      )}

      {dataError && <Alert severity="error" sx={{ mt: 2 }}>{dataError}</Alert>}

      {selectedData && !dataLoading && (
        <AlignmentResultsTable data={selectedData} heading="Alignment Results" />
      )}
    </section>
  );
}
